// Converts design/levels.*.json (Level Designer pack) + design/economy.json into engine data modules.
import fs from 'fs';
const out = [];
for (const p of ['earth', 'moon', 'mars']) {
  const J = JSON.parse(fs.readFileSync(`design/levels.${p}.json`, 'utf8'));
  for (const l of J.levels) {
    const obj = l.objective || {}; const st = l.stars || {};
    const drain = l.battery && typeof l.battery.drainMul === 'number' ? l.battery.drainMul : (l.drainMul || 1);
    const cpSp = l.checkpoints && (l.checkpoints.spacing || l.checkpoints.engineSpacing) || 220;
    out.push({ id: l.id, planet: p, order: l.order, name: l.name, env: l.env, diff: l.diff, blurb: l.blurb, quest: l.quest, storm: l.storm || 0,
      objective: { type: obj.type || 'race', ai: obj.aiRivals ?? 3, pads: obj.pads || null }, stars: st, drainMul: drain, cpSpacing: cpSp,
      volcano: p === 'mars' ? (/olympus/i.test(l.name) ? 'summit' : 'far') : null,
      segments: l.segments });
  }
}
fs.writeFileSync('src/levels.data.js', '// GENERATED by tools/import-design.mjs from design/levels.*.json - do not edit by hand.\nexport const DESIGN_LEVELS = ' + JSON.stringify(out) + ';\n');
const E = JSON.parse(fs.readFileSync('design/economy.json', 'utf8'));
const ids = ['tank', 'speed', 'accel', 'handling', 'boost', 'thruster'];
const tracks = {}; E.upgradeTracks.forEach((t, i) => { tracks[t.key || t.id || ids[i]] = t.tiers.map(x => x.cost); });
const magnet = (E.optionalPerks || []).find(x => x.key === 'magnet');
if (magnet) tracks.magnet = magnet.tiers.map(x => x.cost);
fs.writeFileSync('src/economy.data.js', '// GENERATED by tools/import-design.mjs from design/economy.json\nexport const UPGRADE_COSTS = ' + JSON.stringify(tracks) + ';\n');
console.log(out.length, 'levels;', Object.keys(tracks).map(k => k + ':' + tracks[k].length).join(' '));
